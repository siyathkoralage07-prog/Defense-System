    public void addDefenseObserver(DefenseObserver observer){
        DefenseObserver[] temp = new DefenseObserver[observers.length + 1];
        for(int i = 0; i < observers.length; i++){
            temp[i] = observers[i];
        }
        temp[temp.length - 1] = observer;
        observers = temp;
    }
    
